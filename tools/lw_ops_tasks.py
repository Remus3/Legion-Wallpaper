def _task_json(t: Task) -> dict:
    return {"id": t.id, "cap": t.cap, "subject": t.subject, "reason": t.reason,
            "steps": t.steps, "handoffs": t.handoffs, "state": t.state,
            "attempts": t.attempts, "last_error": t.last_error, "opened": t.opened}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=None)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("request")
    r.add_argument("--cap", required=True)
    r.add_argument("--subject", required=True)
    r.add_argument("--reason", required=True)
    r.add_argument("--step", action="append", default=[])
    r.add_argument("--handoff", action="append", default=[])
    r.add_argument("--verify-json", required=True, help="the verify argv as a JSON list")
    sub.add_parser("pending")
    sub.add_parser("list")
    sub.add_parser("render")
    sub.add_parser("verify-pending")
    d = sub.add_parser("done")
    d.add_argument("id")
    c = sub.add_parser("comment")
    c.add_argument("id")
    c.add_argument("text")
    w = sub.add_parser("withdraw")
    w.add_argument("id")
    w.add_argument("reason")
    args = ap.parse_args(argv)
    eng = default_engine(args.root)
    try:
        if args.cmd == "request":
            tid = eng.request(args.cap, args.subject, args.reason, args.step,
                              json.loads(args.verify_json), handoffs=args.handoff)
            print(json.dumps({"id": tid}))
            return 0
        if args.cmd in ("pending", "list"):
            ts = eng.pending() if args.cmd == "pending" else list(eng.tasks().values())
            print(json.dumps([_task_json(t) for t in ts], indent=2))
            return 0
        if args.cmd == "render":
            sys.stdout.write(render_operator_asks(eng.pending()))
            return 0
        if args.cmd == "verify-pending":
            print(json.dumps(eng.verify_pending()))
            return 0
        if args.cmd == "done":
            res = eng.done(args.id)
            print(json.dumps(res))
            return 0 if res["closed"] else 1
        if args.cmd == "comment":
            eng.comment(args.id, args.text)
            return 0
        if args.cmd == "withdraw":
            eng.withdraw(args.id, args.reason)
            return 0
    except (TaskRefused, TamperedLog, KeyError, ValueError, LockBusy) as exc:
        print(f"refused: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
