"""Verified operator-task engine: an ask closes only when its check passes.

# arch: operator asks as observed facts - append-only hash-chained event log, verify-to-close

WHY (ingest directive P0-1, FLEET-COMMON item 1). Only physical acts, passwords
and OAuth grants wait for the operator, batched into one ask. Until this module
that ask was prose in the hand-off file: nothing recorded whether it was done,
nothing closed it, and the same ask could be raised twice. Here an ask is a TASK
keyed by (capability, subject):

  * a second request for an OPEN key JOINS the open task and notifies nobody;
  * every task carries a reason, human-followable steps, optional ordered
    handoffs (a settings pane, a page to open) and a VERIFY argv;
  * the operator pressing "done" only TRIGGERS the check - the task closes
    only when the check exits 0. Missing, crashing or timed-out = not done;
  * comments never close; withdraw closes with a reason and never re-notifies;
  * open/closed is DERIVED by folding the append-only event log - there is no
    stored state flag to drift from what happened;
  * the log is a hash chain (seq + prev + sha256 per line), so an edited or
    deleted past event is detected and every further write is refused;
  * `verify_pending()` re-runs every open check; it rides the inbox responder's
    5-minute `--once` tick (tools/lw_inbox_responder.py), not a new task.

THE HAND-OFF RENDERS FROM HERE. `tools/lw_next_session.py --write` replaces the
"Operator asks" block of LW-NEXT-SESSION.txt with `render_operator_asks()` over
the pending list, so the batched ask is always current and never hand-written.
This module is the source the hand-off renders from, not a second hand-off.

SAFETY. A verify argv is arbitrary code run unattended:
  * argv must be a non-empty list/tuple of str - a string is refused at the
    API boundary (no shell, ever: `shell=False`);
  * its executable must be on `ALLOWED_EXECUTABLES` (by basename) or be this
    interpreter;
  * only the owning tree (`OWNER`, LW) registers a check - a note from another
    tree never reaches `request()`; the CLI is the only registration path;
  * every run gets CREATE_NO_WINDOW and a timeout.

NOTIFICATIONS go through a pluggable sink whose `send(message)` returns
(ok, detail); the engine wraps it so a sink never raises into a caller. Default
`FileSink` (ops/runtime/operator_tasks/notifications.jsonl). `LW_OPS_TASKS_HOLD`
set to anything non-empty makes every send a no-op recorded as "held".

Runtime root: `ops/runtime/operator_tasks/` (gitignored), overridable through
`LW_OPS_TASKS_ROOT` - the suite points it at a per-test dir (tests/conftest.py).

CLI:
    python tools/lw_ops_tasks.py request --cap physical --subject dac \\
        --reason "..." --step "..." [--handoff "..."] --verify-json '["python","-c","..."]'
    python tools/lw_ops_tasks.py pending | list | render
    python tools/lw_ops_tasks.py done T0001          # exit 0 only if it closed
    python tools/lw_ops_tasks.py comment T0001 "text"
    python tools/lw_ops_tasks.py withdraw T0001 "reason"
    python tools/lw_ops_tasks.py verify-pending
Coverage: tests/test_lw_ops_tasks.py.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)

ROOT_ENV = "LW_OPS_TASKS_ROOT"
HOLD_ENV = "LW_OPS_TASKS_HOLD"
OWNER = "LW"
VERIFY_TIMEOUT_S = 60.0

# By lower-cased basename. Interpreters and read-only probes this tree already
# runs; a shell (cmd, powershell, bash) is deliberately absent - a verify that
# needs one is a script file run by python.
ALLOWED_EXECUTABLES = frozenset({
    "python", "python.exe", "python3", "python3.exe", "pythonw.exe", "py.exe",
    "git", "git.exe", "gh", "gh.exe", "schtasks", "schtasks.exe",
    "where.exe", "reg.exe", "sc.exe",
})

ASKS_BEGIN = ("Operator asks (generated by tools/lw_ops_tasks.py from the open-task "
              "log; do not edit by hand):")
ASKS_END = "  (end operator asks)"

LOCK_WAIT_S = 10.0


class TaskRefused(ValueError):
    """A request the engine will not record (bad argv, foreign owner, ...)."""


class TamperedLog(RuntimeError):
    """The event log's hash chain does not hold: a past event was edited/lost."""


def default_root() -> Path:
    env = os.environ.get(ROOT_ENV, "").strip()
    return Path(env) if env else ROOT / "ops" / "runtime" / "operator_tasks"


def _now() -> str:
    return dt.datetime.now(dt.UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _digest(event: dict) -> str:
    body = {k: v for k, v in event.items() if k != "hash"}
    return hashlib.sha256(json.dumps(body, sort_keys=True).encode("utf-8")).hexdigest()


# Single-writer lock: lw_watch's pid-stamped lock dir (liveness by pid, never mtime)
try:
    from lw_watch import LockBusy, pid_alive, watch_lock as pid_lock  # noqa: F401
except ImportError:  # running with tools/ off sys.path
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from lw_watch import LockBusy, pid_alive, watch_lock as pid_lock  # noqa: F401


