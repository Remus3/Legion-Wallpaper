# Store
# ---------------------------------------------------------------------------

class JsonlTaskStore:
    """Append-only JSONL event log with a sha256 hash chain.

    Each line: {..., "seq": n, "prev": <hash of line n-1 or "">, "hash": ...}.
    `read()` verifies the whole chain and raises TamperedLog on any break;
    `append()` holds a single-writer lock and re-verifies before writing, so a
    tampered log is never extended.
    """

    def __init__(self, path: Path):
        self.path = Path(path)
        self.lock_dir = self.path.with_name(self.path.name + ".lock")

    def read(self) -> list[dict]:
        if not self.path.exists():
            return []
        events, prev = [], ""
        text = self.path.read_text(encoding="utf-8")
        for n, line in enumerate(text.splitlines(), 1):
            if not line.strip():
                continue
            try:
                ev = json.loads(line)
            except ValueError:
                raise TamperedLog(f"line {n} is not JSON") from None
            if not isinstance(ev, dict):
                raise TamperedLog(f"line {n} is not an object")
            if ev.get("seq") != len(events) + 1:
                raise TamperedLog(f"line {n}: sequence break (seq {ev.get('seq')!r})")
            if ev.get("prev") != prev:
                raise TamperedLog(f"line {n}: chain break (prev does not match)")
            if ev.get("hash") != _digest(ev):
                raise TamperedLog(f"line {n}: content does not match its hash")
            prev = ev["hash"]
            events.append(ev)
        return events

    def append(self, event: dict) -> dict:
        with pid_lock(self.lock_dir, wait_s=LOCK_WAIT_S):
            events = self.read()
            ev = dict(event)
            ev["seq"] = len(events) + 1
            ev["prev"] = events[-1]["hash"] if events else ""
            ev["hash"] = _digest(ev)
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.path.open("a", encoding="utf-8", newline="\n") as fh:
                fh.write(json.dumps(ev, sort_keys=True) + "\n")
                fh.flush()
                os.fsync(fh.fileno())
            return ev


# ---------------------------------------------------------------------------
# Sinks
# ---------------------------------------------------------------------------

class FileSink:
    """Append each notification as one JSON line. Returns (ok, detail)."""

    def __init__(self, path: Path):
        self.path = Path(path)

    def send(self, message: dict):
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            with self.path.open("a", encoding="utf-8", newline="\n") as fh:
                fh.write(json.dumps({"ts": _now(), **message}, sort_keys=True) + "\n")
            return True, f"appended to {self.path.name}"
        except OSError as exc:
            return False, f"{type(exc).__name__}"


# ---------------------------------------------------------------------------
# Verify runner
# ---------------------------------------------------------------------------

def validate_argv(argv) -> list[str]:
    """The argv as a list of str, or TaskRefused. Never a string, never a shell."""
    # One test covers str and bytes: neither is a list/tuple.
    if not isinstance(argv, (list, tuple)) or not argv:
        raise TaskRefused("verify argv must be a non-empty list of arguments "
                          f"(got {type(argv).__name__}) - never a string")
    if not all(isinstance(a, str) and a != "" for a in argv):
        raise TaskRefused("every verify argument must be a non-empty string")
    exe = argv[0]
    same = os.path.normcase(os.path.abspath(exe)) == os.path.normcase(sys.executable)
    if not same and Path(exe).name.lower() not in ALLOWED_EXECUTABLES:
        raise TaskRefused(f"executable {Path(exe).name!r} is not on the allowlist")
    return list(argv)


def run_verify(argv, timeout_s: float = VERIFY_TIMEOUT_S) -> dict:
    """Run the check. {"passed", "rc", "error"}; never raises."""
    try:
        argv = validate_argv(argv)
    except TaskRefused as exc:
        return {"passed": False, "rc": None, "error": f"refused: {exc}"}
    try:
        r = subprocess.run(argv, shell=False, capture_output=True, timeout=timeout_s,
                           stdin=subprocess.DEVNULL, creationflags=NO_WINDOW)
    except subprocess.TimeoutExpired:
        return {"passed": False, "rc": None, "error": "timeout"}
    except OSError as exc:
        return {"passed": False, "rc": None, "error": f"{type(exc).__name__}"}
    err = ""
    if r.returncode != 0:
        tail = (r.stderr or b"").decode("utf-8", "replace").strip().splitlines()
        err = tail[-1][:200] if tail else f"exit {r.returncode}"
    return {"passed": r.returncode == 0, "rc": r.returncode, "error": err}


