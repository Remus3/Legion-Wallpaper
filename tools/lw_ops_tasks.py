@dataclass
class Task:
    id: str
    cap: str
    subject: str
    reason: str
    steps: list
    handoffs: list
    verify_argv: list
    owner: str
    opened: str
    state: str = "open"            # open | closed | withdrawn - derived, never stored
    comments: list = field(default_factory=list)
    attempts: int = 0
    last_error: str = ""


def fold(events: list[dict]) -> dict[str, Task]:
    """Derive every task's state from the event log."""
    tasks: dict[str, Task] = {}
    for ev in events:
        kind, tid = ev.get("kind"), ev.get("task")
        if kind == "request":
            tasks[tid] = Task(tid, ev["cap"], ev["subject"], ev["reason"], list(ev["steps"]),
                              list(ev.get("handoffs") or []), list(ev["verify_argv"]),
                              ev["owner"], ev["ts"])
            continue
        t = tasks.get(tid)
        if t is None:
            continue
        if kind == "comment":
            t.comments.append(ev.get("text", ""))
        elif kind == "verify":
            t.attempts += 1
            t.last_error = "" if ev.get("passed") else str(ev.get("error") or "")
        elif kind == "close" and t.state == "open":
            t.state = "closed"
        elif kind == "withdraw" and t.state == "open":
            t.state = "withdrawn"
    return tasks


class TaskEngine:
    def __init__(self, store: JsonlTaskStore, sink=None, *,
                 verify_timeout_s: float = VERIFY_TIMEOUT_S, runner=run_verify):
        self.store = store
        self.sink = sink if sink is not None else FileSink(store.path.with_name(
            "notifications.jsonl"))
        self.verify_timeout_s = verify_timeout_s
        self.runner = runner

    # -- reads --------------------------------------------------------------
    def tasks(self) -> dict[str, Task]:
        return fold(self.store.read())

    def task(self, tid: str) -> Task:
        t = self.tasks().get(tid)
        if t is None:
            raise KeyError(tid)
        return t

    def pending(self) -> list[Task]:
        return [t for t in self.tasks().values() if t.state == "open"]

    # -- writes -------------------------------------------------------------
    def _event(self, kind: str, tid: str, **fields) -> dict:
        return self.store.append({"kind": kind, "task": tid, "ts": _now(), **fields})

    def request(self, cap: str, subject: str, reason: str, steps, verify_argv,
                handoffs=None, owner: str = OWNER) -> str:
        if owner != OWNER:
            raise TaskRefused(f"owner {owner!r} may not register a check in {OWNER}")
        argv = validate_argv(verify_argv)
        for name, val in (("cap", cap), ("subject", subject), ("reason", reason)):
            if not isinstance(val, str) or not val.strip():
                raise TaskRefused(f"{name} must be a non-empty string")
        steps = [str(s) for s in (steps or [])]
        if not steps:
            raise TaskRefused("a task needs at least one human-followable step")
        events = self.store.read()
        for t in fold(events).values():
            if t.state == "open" and (t.cap, t.subject) == (cap, subject):
                self._event("join", t.id, reason=reason)
                return t.id
        tid = f"T{1 + sum(1 for e in events if e.get('kind') == 'request'):04d}"
        self._event("request", tid, cap=cap, subject=subject, reason=reason, steps=steps,
                    handoffs=[str(h) for h in (handoffs or [])], verify_argv=argv,
                    owner=owner)
        self._notify(tid, {"task": tid, "cap": cap, "subject": subject, "reason": reason})
        return tid

    def _notify(self, tid: str, message: dict) -> None:
        if os.environ.get(HOLD_ENV, "").strip():
            ok, detail = False, "held"
        else:
            try:
                ok, detail = self.sink.send(message)
                ok, detail = bool(ok), str(detail)
            except Exception as exc:  # noqa: BLE001 - a sink never raises into us
                ok, detail = False, f"sink raised {type(exc).__name__}"
        self._event("notify", tid, ok=ok, detail=detail)

    def comment(self, tid: str, text: str) -> None:
        self.task(tid)
        self._event("comment", tid, text=str(text))

    def withdraw(self, tid: str, reason: str) -> None:
        t = self.task(tid)
        if t.state == "open":
            self._event("withdraw", tid, reason=str(reason))

    def _check(self, t: Task, trigger: str) -> bool:
        res = self.runner(t.verify_argv, timeout_s=self.verify_timeout_s)
        self._event("verify", t.id, trigger=trigger, passed=bool(res.get("passed")),
                    rc=res.get("rc"), error=str(res.get("error") or ""))
        if res.get("passed"):
            self._event("close", t.id, by=trigger)
            return True
        return False

    def done(self, tid: str) -> dict:
        """The operator says done: run the check; close only on exit 0."""
        t = self.task(tid)
        if t.state != "open":
            return {"task": tid, "closed": t.state == "closed", "state": t.state}
        closed = self._check(t, "done")
        return {"task": tid, "closed": closed, "state": "closed" if closed else "open"}

    def verify_pending(self) -> dict:
        """Re-run every open check (the scheduled pass)."""
        out = {"checked": [], "closed": [], "open": []}
        for t in self.pending():
            out["checked"].append(t.id)
            (out["closed"] if self._check(t, "scheduled") else out["open"]).append(t.id)
        return out


def default_engine(root: Path | None = None) -> TaskEngine:
    r = Path(root) if root is not None else default_root()
    return TaskEngine(JsonlTaskStore(r / "events.jsonl"), FileSink(r / "notifications.jsonl"))


# ---------------------------------------------------------------------------
# Hand-off rendering
# ---------------------------------------------------------------------------

def _gate(lines: list[str]) -> list[str]:
    try:
        from precommit_gate import scan_handoff_text
    except ImportError:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        from precommit_gate import scan_handoff_text
    return scan_handoff_text("\n".join(lines))


def render_operator_asks(tasks: list[Task]) -> str:
    """The hand-off's "Operator asks" block, from the pending task list.

    The verify argv is never rendered (it may carry a path). A task whose own
    text would fail the hand-off content gate is listed by id only.
    """
    out = [ASKS_BEGIN]
    if not tasks:
        out.append("  none open")
    for t in tasks:
        lines = [f"  - {t.id} {t.cap}/{t.subject}: {t.reason}",
                 "      steps: " + "; ".join(f"{i}) {s}" for i, s in enumerate(t.steps, 1))]
        if t.handoffs:
            lines.append("      open first: " + " -> ".join(t.handoffs))
        if t.last_error:
            lines.append(f"      last check: not done ({t.attempts} tries)")
        if _gate(lines):
            lines = [f"  - {t.id} {t.cap}: text withheld (fails the hand-off gate); "
                     f"see python tools/lw_ops_tasks.py pending"]
        out.extend(lines)
        out.append(f"      close: python tools/lw_ops_tasks.py done {t.id} "
                   "(closes only when its check passes)")
    out.append(ASKS_END)
    return "\n".join(out) + "\n"


def inject_operator_asks(text: str, engine: TaskEngine | None = None) -> str:
    """Replace (or append) the generated block. Never raises."""
    eng = engine if engine is not None else default_engine()
    try:
        block = render_operator_asks(eng.pending())
    except Exception as exc:  # noqa: BLE001 - /done must never fail on this
        block = (f"{ASKS_BEGIN}\n  UNKNOWN - task log unreadable "
                 f"({type(exc).__name__}); run python tools/lw_ops_tasks.py pending\n"
                 f"{ASKS_END}\n")
    lines = text.splitlines(keepends=True)
    kept, skipping = [], False
    for line in lines:
        bare = line.rstrip("\r\n")
        if bare == ASKS_BEGIN:
            skipping = True
            continue
        if skipping:
            if bare == ASKS_END:
                skipping = False
            continue
        kept.append(line)
    body = "".join(kept)
    if body and not body.endswith("\n"):
        body += "\n"
    return body + block


